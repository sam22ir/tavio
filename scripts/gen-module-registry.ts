import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { validateGraph } from '../src/core/modules/graph';
import type { ModuleManifest } from '../src/core/modules/define';

const ROOT = process.cwd();
const MODULES_DIR = path.join(ROOT, 'src', 'modules');
const OUT_FILE = path.join(ROOT, 'src', 'core', 'modules', 'registry.generated.ts');

function isModuleManifest(value: unknown): value is ModuleManifest {
  if (typeof value !== 'object' || value === null) return false;
  const m = value as Record<string, unknown>;
  return (
    typeof m.id === 'string' &&
    typeof m.name === 'string' &&
    typeof m.version === 'string' &&
    Array.isArray(m.depends) &&
    Array.isArray(m.permissions) &&
    Array.isArray(m.menus)
  );
}

function findManifestFolders(): string[] {
  if (!existsSync(MODULES_DIR)) return [];
  return readdirSync(MODULES_DIR)
    .filter((name) => statSync(path.join(MODULES_DIR, name)).isDirectory())
    .filter((name) => existsSync(path.join(MODULES_DIR, name, 'manifest.ts')))
    .sort();
}

async function main(): Promise<number> {
  const folders = findManifestFolders();
  const mods: ModuleManifest[] = [];
  const errors: string[] = [];

  for (const folder of folders) {
    const file = path.join(MODULES_DIR, folder, 'manifest.ts');
    const loaded: unknown = await import(pathToFileURL(file).href);
    const manifest: unknown =
      typeof loaded === 'object' && loaded !== null && 'manifest' in loaded ? loaded.manifest : undefined;
    if (!isModuleManifest(manifest)) {
      errors.push(`${folder}: manifest.ts must export a named "manifest" from defineModule()`);
      continue;
    }
    if (manifest.id !== folder) {
      errors.push(`${folder}: manifest id "${manifest.id}" must match its folder name`);
      continue;
    }
    mods.push(manifest);
  }

  const graph = validateGraph(mods);
  if (!graph.ok) {
    for (const [id, dep] of graph.missing) errors.push(`${id}: missing dependency "${dep}"`);
    for (const cycle of graph.cycles) errors.push(`dependency cycle: ${cycle.join(' -> ')}`);
  }

  if (errors.length > 0) {
    for (const e of errors) console.error(`modules:gen error: ${e}`);
    return 1;
  }

  const imports = folders.map(
    (folder) => `import { manifest as m_${folder} } from '@/modules/${folder}/manifest';`,
  );
  const list = folders.map((folder) => `m_${folder}`).join(', ');
  const source = [
    '// Generated by scripts/gen-module-registry.ts (pnpm modules:gen). Do not edit.',
    "import type { ModuleManifest } from '@/core/modules/define';",
    ...imports,
    '',
    `export const modules: readonly ModuleManifest[] = [${list}];`,
    '',
  ].join('\n');

  writeFileSync(OUT_FILE, source);
  console.log(`modules:gen wrote ${folders.length} module(s) to ${path.relative(ROOT, OUT_FILE)}`);
  return 0;
}

main().then(
  (code) => {
    process.exitCode = code;
  },
  (error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  },
);
